const PIC_ALIAS = { inclinepush: 'incline', assist: 'pullup', chinup: 'pullup', closepush: 'pushup', pushbottom: 'pushhalf', couch: 'hipflex', lungehold: 'lunge', split: 'lunge', handstand: 'pike', row: 'scap' };
/* Rank-specific pictures (movement level 0) */
const PIC_LEVEL = { 'pushup:0': 'kneepush' };

function picSVG(id, li) {
  const key = PIC_LEVEL[id + ':' + li] || PIC_ALIAS[id] || id;
  const p = PICS[key];
  if (!p) return '';
  const line = (pts) => `<polyline points="${pts.join(',').replace(/(\d+,\d+),/g, '$1 ')}"/>`;
  const fig = (a, extra) => {
    const [hx, hy, sx, sy, px, py, kx, ky, fx, fy, ex, ey, wx, wy, c = 0] = a;
    return `<path d="M${sx} ${sy}Q${(sx + px) / 2} ${(sy + py) / 2 + c} ${px} ${py}"/>` +
      line([px, py, kx, ky, fx, fy]) + line([sx, sy, ex, ey, wx, wy]) +
      `<circle cx="${hx}" cy="${hy}" r="4" class="hd"/>` + (extra || []).map(line).join('');
  };
  const frames = p.f.map((a, i) => {
    let ex = p.x2 ? p.x2[i] : p.x;
    if (p.xs) ex = p.x[i];
    return `<g class="fr ${i ? 'b' : 'a'}">${fig(a, ex)}</g>`;
  }).join('');
  return `<svg viewBox="0 0 120 62" class="pic${p.f.length > 1 ? ' anim' : ''}" role="img" aria-label="Exercise position">` +
    (p.g === 0 ? '' : '<line x1="6" y1="56" x2="114" y2="56" class="gr"/>') + (p.d || '') + frames + '</svg>';
}
